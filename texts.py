ENDINGS = [
    "",
    "",
    "کاش برگردی.",
    "هنوز دوستت دارم.",
    "دلم هنوز مال توئه.",
    "برگرد...",
    "بی‌تو سخته.",
    "تو رو کم دارم.",
]


def random_sentence():
    opener = random.choice(OPENERS)
    feeling = random.choice(FEELINGS)
    ending = random.choice(ENDINGS)
    s = f"{opener} {feeling}."
    if ending:
        s += f" {ending}"
    return s


def unique_sentence(db):
    """A sentence that was never used before (falls back to any sentence)."""
    s = random_sentence()
    for _ in range(30):
        if not db.text_used("sentence", s):
            break
        s = random_sentence()
    db.mark_text("sentence", s)
    return s


